"""Madinah AutoGluon V4 -- conservative frozen camera diagnostic.

Reads V2 forward-date CV predictions generated by madinah_autogluon_v2.py.
Does NOT train models, use test labels, create a Kaggle submission or upload.
Candidate selection is EARLY day only, assessment is LATER day. All tests
remain exploratory because V2 used both days for choosing its global champion.

PowerShell:
  .\\.venv-ag\\Scripts\\python.exe .\\madinah_autogluon_v4_frozen_camera.py
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

BASE = 'sp_rule_50'
COLS = ['recording', 'day', 'unit', 'minute_of_day', 'kind', 'people',
        'sp_rule_50', 'pooled', 'specialists', 'rules_only']
# Only high-error cameras previously identified for pre-declared investigation.
FOCUS = [('forecast', 'cam_E'), ('forecast', 'cam_A'), ('forecast', 'cam_F'),
         ('missing', 'cam_A'), ('missing', 'cam_E')]
# Existing AutoGluon predictions, with no new model training.
CANDIDATES = ['pooled', 'rules_only', 'specialists', 'half_pooled_specialists',
              'half_specialists_rules']


def safe_mae(actual, predicted):
    if len(actual) == 0:
        return None
    return float(np.abs(actual - predicted).mean())


def compute_pools(df):
    result = {n: pd.to_numeric(df[n], errors='raise').to_numpy(dtype=float)
              for n in ['sp_rule_50', 'pooled', 'specialists', 'rules_only']}
    result['half_pooled_specialists'] = 0.5 * (result['pooled'] + result['specialists'])
    result['half_specialists_rules'] = 0.5 * (result['specialists'] + result['rules_only'])
    if any((~np.isfinite(a)).any() or (a < 0).any() for a in result.values()):
        raise ValueError('Nonfinite/negative predictions detected')
    return result


def evaluate(input_path, out_dir, min_rows, min_gain, min_positive_blocks, soft_weight):
    if not input_path.is_file():
        raise FileNotFoundError(f'Missing {input_path}; run V2 --mode validate first.')
    df = pd.read_csv(input_path)
    missing = sorted(set(COLS) - set(df.columns))
    if missing:
        raise ValueError(f'CSV missing columns: {missing}')
    if df.empty or df.duplicated(['recording', 'unit', 'minute_of_day', 'kind']).any():
        raise ValueError('Empty or duplicate validation targets')
    df = df.copy()
    for c in ['day', 'unit', 'kind']:
        if df[c].isna().any():
            raise ValueError(f'Missing value in {c}')
    df['minute_of_day'] = pd.to_numeric(df['minute_of_day'], errors='raise')
    y = pd.to_numeric(df['people'], errors='raise').to_numpy(float)
    if (~np.isfinite(y)).any() or (y < 0).any():
        raise ValueError('Invalid true people counts')
    pool = compute_pools(df)
    days = sorted(df['day'].astype(str).unique())
    if len(days) != 2:
        raise ValueError(f'Expected exactly two chronological holdout days; found {days}')
    early = df['day'].astype(str).eq(days[0]).to_numpy()
    late = ~early
    b = pool[BASE]
    chosen = b.copy()
    policies = []
    # These candidate groups are declared before looking at target values.
    for kind, cam in FOCUS:
        group = df['kind'].astype(str).eq(kind).to_numpy() & df['unit'].astype(str).eq(cam).to_numpy()
        mask = early & group
        n = int(mask.sum())
        record = {'kind': kind, 'unit': cam, 'early_n': n, 'late_n': int((late & group).sum()),
                  'early_base_mae': safe_mae(y[mask], b[mask]),
                  'selected': BASE, 'early_gain_pct': 0., 'positive_blocks': 0, 'blocks': 0}
        if n >= min_rows:
            candidates = []
            base_early = np.abs(y[mask] - b[mask])
            for name in CANDIDATES:
                # Softening guards against large switches from the V2 anchor.
                p = (1. - soft_weight) * b + soft_weight * pool[name]
                new_err = np.abs(y[mask] - p[mask])
                gain = 100 * (base_early.mean() - new_err.mean()) / max(1e-9, base_early.mean())
                # Group contiguous minutes into 20-minute blocks to reduce false confidence
                # from temporally correlated rows. For any camera, at least several blocks
                # must benefit; selecting based on the later day is forbidden.
                block_ids = (df.loc[mask, 'minute_of_day'].to_numpy() // 20).astype(int)
                block_gains = [float((base_early[block_ids == k] - new_err[block_ids == k]).mean())
                               for k in np.unique(block_ids) if (block_ids == k).sum() >= 3]
                positive = sum(x > 0 for x in block_gains)
                candidates.append((gain, name, positive, len(block_gains)))
            candidates.sort(key=lambda x: (-x[0], x[1]))
            gain, name, positive, total = candidates[0]
            record.update({'best_early_candidate': name, 'best_early_gain_pct': float(gain),
                           'positive_blocks': int(positive), 'blocks': int(total)})
            # Freeze early-only choice, with a hurdle against overfitting.
            if gain >= min_gain and total >= min_positive_blocks and positive >= min_positive_blocks and positive / total >= 0.60:
                chosen[group] = (1. - soft_weight) * b[group] + soft_weight * pool[name][group]
                record['selected'] = name
                record['early_gain_pct'] = float(gain)
        policies.append(record)

    def score(day_mask):
        base_mae = safe_mae(y[day_mask], b[day_mask])
        new_mae = safe_mae(y[day_mask], chosen[day_mask])
        gain = 100 * (base_mae - new_mae) / base_mae if base_mae and new_mae is not None else 0.
        return {'n': int(day_mask.sum()), 'v2_mae_people': base_mae,
                'v4_mae_people': new_mae, 'gain_percent': float(gain)}

    rows = []
    for day in days:
        dmask = df['day'].astype(str).eq(day).to_numpy()
        for (kind, unit), group in df.groupby(['kind', 'unit'], sort=True):
            mask = dmask & df['kind'].astype(str).eq(kind).to_numpy() & df['unit'].astype(str).eq(unit).to_numpy()
            if not mask.any():
                continue
            r = score(mask)
            r.update({'day': day, 'kind': kind, 'unit': unit,
                      'v2_abs_error_sum': float(np.abs(y[mask]-b[mask]).sum())})
            rows.append(r)
    table = pd.DataFrame(rows)
    second = table[table['day'].eq(days[1])]
    # Severe subgroup deterioration veto, large enough to be meaningful.
    severe = second[(second['n'] >= 40) &
                    (second['v4_mae_people'] > 1.10 * second['v2_mae_people'])]
    late_stats = score(late)
    passed = late_stats['gain_percent'] >= 2. and severe.empty and any(x['selected'] != BASE for x in policies)
    verdict = 'PASS_SHADOW_DIAGNOSTIC_ONLY' if passed else 'KEEP_V2'
    summary = {'description': 'V4 early-only per-camera policy, soft changes to existing AutoGluon V2 predictions',
               'warning': 'Exploratory diagnostic: V2 model selection previously saw both held-out dates. This is NOT unbiased validation or the official Kaggle score.',
               'days': days, 'early': score(early), 'later': late_stats, 'combined': score(np.ones(len(df), bool)),
               'focus_groups': policies, 'severe_regressions_later': severe.to_dict('records'),
               'verdict': verdict, 'competition_score_verified': False,
               'no_models_trained': True, 'no_submission_created': True,
               'parameters': {'min_rows': min_rows, 'min_gain_percent': min_gain,
                              'min_positive_blocks': min_positive_blocks, 'soft_weight': soft_weight}}
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir/'ag_v4_frozen_camera_summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding='utf-8')
    table.sort_values(['day', 'v2_abs_error_sum'], ascending=[True, False]).to_csv(
        out_dir/'ag_v4_frozen_camera_by_camera.csv', index=False)
    print('=== V4 FROZEN CAMERA SHADOW TEST (NO RETRAINING) ===')
    print('Days:', ' -> '.join(days))
    print('Note: Fridays and Saturdays can have different regimes; results are exploratory.')
    print('Selected on early day ONLY:')
    for p in policies:
        print(f"  {p['kind']:15} {p['unit']:7} n={p['early_n']:3} -> {p['selected']}")
    for name, val in [('Early', summary['early']), ('Later', summary['later']), ('Combined', summary['combined'])]:
        print(f"{name:8}: V2={val['v2_mae_people']:.4f} V4={val['v4_mae_people']:.4f} gain={val['gain_percent']:+.2f}%")
    print('VERDICT:', verdict)
    print('Saved: reports/ag_v4_frozen_camera_summary.json and reports/ag_v4_frozen_camera_by_camera.csv')
    print('No Kaggle submission created or uploaded. These MAEs are NOT Kaggle scores.')
    return summary


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--input', type=Path, default=Path('reports/ag_v2_cv_predictions.csv'))
    p.add_argument('--reports', type=Path, default=Path('reports'))
    p.add_argument('--min-rows', type=int, default=60)
    p.add_argument('--min-gain-percent', type=float, default=5.0)
    p.add_argument('--min-positive-blocks', type=int, default=4)
    p.add_argument('--soft-weight', type=float, default=0.5)
    args = p.parse_args()
    if args.min_rows < 10 or args.min_gain_percent < 0 or args.min_positive_blocks < 1 or not (0 < args.soft_weight <= 1):
        p.error('Invalid min_rows/min_gain/min_positive_blocks/soft_weight')
    evaluate(args.input, args.reports, args.min_rows, args.min_gain_percent,
             args.min_positive_blocks, args.soft_weight)


if __name__ == '__main__':
    main()
